import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import mysql from 'mysql2/promise';
import express from 'express';
import bcrypt from 'bcryptjs';
import { readFile, mkdir } from 'node:fs/promises';
import { once } from 'node:events';
import { fileURLToPath } from 'node:url';
import { criarApp } from '../backend/app.js';
import { criarRepositorio } from '../backend/repository.js';
import '../backend/config.js';

const db = 'barbearia_visual_test';
const config = { host: process.env.DB_HOST || '127.0.0.1', port: Number(process.env.DB_PORT || 3306), user: process.env.DB_USER || 'root', password: process.env.DB_PASSWORD || '', multipleStatements: true, dateStrings: true };
const conexao = await mysql.createConnection(config);
let criada = false, pool, servidor, web, browser;
try {
  await conexao.query('CREATE DATABASE ' + db + ' CHARACTER SET utf8mb4'); criada = true;
  const sql = (await readFile(new URL('../database/barbearia.sql', import.meta.url), 'utf8')).replace(/CREATE DATABASE[^;]+;/, '').replace('USE barbearia_agenda;', 'USE ' + db + ';');
  await conexao.query(sql);
  pool = mysql.createPool({ ...config, database: db, multipleStatements: false });
  const repo = criarRepositorio(pool);
  await repo.criarUsuario('Administrador', 'admin@teste.local', await bcrypt.hash('SenhaTeste123', 4), 'admin');
  const d = new Date(); d.setDate(d.getDate() + 5); const data = d.toISOString().slice(0, 10);
  for (const hora of ['09:00', '10:00', '11:00']) await repo.criar({ data, hora });
  servidor = criarApp(repo, 'segredo-exclusivo-para-testes-de-interface-12345', { limitar: false }).listen(3000, '127.0.0.1');
  await once(servidor, 'listening');
  web = express().use(express.static(fileURLToPath(new URL('../dist', import.meta.url)))).listen(8080, '127.0.0.1');
  await once(web, 'listening');
  await mkdir('test-results', { recursive: true });
  browser = await chromium.launch({ headless: true });
  const pagina = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  const erros = []; pagina.on('pageerror', e => erros.push(e.message));
  await pagina.goto('http://127.0.0.1:8080');
  await pagina.getByRole('button', { name: 'Entrar na minha conta', exact: true }).waitFor();
  await pagina.screenshot({ path: 'test-results/01-login-mobile.png', fullPage: true });
  await pagina.getByRole('button', { name: 'Primeira vez? Criar conta' }).click();
  await pagina.getByLabel('Nome completo', { exact: true }).fill('Rafael Teste');
  await pagina.getByLabel('E-mail', { exact: true }).fill('rafael@teste.local');
  await pagina.getByLabel('Senha', { exact: true }).fill('SenhaTeste123');
  await pagina.getByRole('button', { name: 'Criar minha conta', exact: true }).click();
  await pagina.getByText('Sua conta está pronta.', { exact: false }).waitFor();
  await pagina.getByLabel('Senha', { exact: true }).fill('SenhaTeste123');
  await pagina.getByRole('button', { name: 'Entrar na minha conta', exact: true }).click();
  await pagina.getByRole('button', { name: 'Agendar 09:00', exact: true }).waitFor();
  assert.equal(await pagina.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Sem overflow horizontal no celular');
  await pagina.screenshot({ path: 'test-results/02-agenda-mobile.png', fullPage: true });
  await pagina.getByRole('button', { name: 'Agendar 09:00', exact: true }).click();
  await pagina.getByText('Reserva confirmada.', { exact: false }).waitFor();
  await pagina.getByRole('button', { name: 'Meus agendamentos (1)', exact: true }).click();
  await pagina.getByRole('button', { name: 'Cancelar reserva das 09:00', exact: true }).waitFor();
  await pagina.screenshot({ path: 'test-results/03-reserva-mobile.png', fullPage: true });
  await pagina.getByRole('button', { name: 'Cancelar reserva das 09:00', exact: true }).click();
  await pagina.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await pagina.getByText('Reserva cancelada.', { exact: false }).waitFor();
  await pagina.getByRole('button', { name: 'Escolher outro horário' }).click();
  await pagina.getByRole('button', { name: 'Sair da conta', exact: true }).click();
  await pagina.getByLabel('E-mail', { exact: true }).fill('admin@teste.local');
  await pagina.getByLabel('Senha', { exact: true }).fill('SenhaTeste123');
  await pagina.getByRole('button', { name: 'Entrar na minha conta', exact: true }).click();
  await pagina.getByRole('button', { name: 'Abrir novo horário', exact: true }).waitFor();
  await pagina.screenshot({ path: 'test-results/04-admin-mobile.png', fullPage: true });
  await pagina.getByRole('button', { name: 'Abrir novo horário', exact: true }).click();
  await pagina.getByLabel('Data (AAAA-MM-DD)', { exact: true }).fill(data);
  await pagina.getByLabel('Hora (HH:00)', { exact: true }).fill('15:00');
  await pagina.getByRole('button', { name: 'Abrir horário', exact: true }).click();
  await pagina.getByRole('button', { name: 'Editar 15:00', exact: true }).click();
  await pagina.getByLabel('Hora (HH:00)', { exact: true }).fill('16:00');
  await pagina.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
  await pagina.getByRole('button', { name: 'Excluir 16:00', exact: true }).click();
  await pagina.getByRole('button', { name: 'Confirmar', exact: true }).click();
  await pagina.getByText('Horário excluído.', { exact: true }).waitFor();
  await pagina.setViewportSize({ width: 1440, height: 1000 });
  await pagina.evaluate(() => { document.querySelectorAll('*').forEach(el => { el.scrollTop = 0; }); });
  await pagina.screenshot({ path: 'test-results/05-admin-desktop.png', fullPage: true });
  assert.equal(await pagina.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Sem overflow horizontal');
  // Confere o comportamento do aplicativo ao receber uma sessão inválida do servidor.
  await pagina.route('**/horarios', route => route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ mensagem: 'Sua sessão expirou. Entre novamente.' }) }));
  await pagina.getByRole('button', { name: 'Atualizar agenda', exact: true }).click();
  await pagina.getByRole('button', { name: 'Entrar na minha conta', exact: true }).waitFor();
  await pagina.getByText('Sua sessão expirou. Entre novamente.', { exact: true }).waitFor();
  await pagina.unroute('**/horarios');
  assert.deepEqual(erros, [], 'Sem erros JavaScript');
  console.log('PASSOU: cadastro, login, reserva, cancelamento, logout, perfil admin, criar/editar/excluir, retorno após 401 e layout mobile/desktop.');
} finally {
  await browser?.close();
  if (servidor) await new Promise(r => servidor.close(r));
  if (web) await new Promise(r => web.close(r));
  await pool?.end();
  if (criada) await conexao.query('DROP DATABASE ' + db);
  await conexao.end();
}
